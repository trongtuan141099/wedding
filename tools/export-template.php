<?php
/** Publish saved invitation content to Git. Never exports guest records or credentials. */
if(PHP_SAPI!=='cli'){http_response_code(404);exit;}
require dirname(__DIR__).'/bootstrap.php';
$project=dirname(__DIR__);
$root=store_state();
$empty=['revision'=>0,'responses'=>[],'wishes'=>[],'rates'=>[],'invitees'=>[]];
$publish=function(array $config)use($project):array{
 $config=validate_config($config);
 $copy=function(string $url)use($project):string{
  if(!str_starts_with($url,'uploads/'))return $url;
  if(!preg_match('~^uploads/[a-zA-Z0-9_.-]+\.(jpg|jpeg|png|webp|mp3|ogg)$~iD',$url,$match))throw new RuntimeException('Unsupported template media.');
  $file=realpath($project.'/'.$url);$uploads=realpath($project.'/uploads');
  if(!$file||!$uploads||dirname($file)!==$uploads)throw new RuntimeException('Template media missing or outside uploads.');
  $target='assets/template-'.substr(hash_file('sha256',$file),0,20).'.'.strtolower($match[1]);
  if(!is_file($project.'/'.$target)&&!copy($file,$project.'/'.$target))throw new RuntimeException('Cannot copy template media.');
  chmod($project.'/'.$target,0644);return $target;
 };
 foreach([['hero','image'],['music','src'],['sharing','image']] as [$section,$key])$config[$section][$key]=$copy($config[$section][$key]);
 $config['gallery']['items']=array_map($copy,$config['gallery']['items']);
 foreach($config['banks']['items'] as &$bank)$bank['qr']=$copy($bank['qr']);unset($bank);
 // A clone derives its public URL from its own domain and installation directory.
 $config['sharing']['baseUrl']='';return $config;
};
$template=array_merge($empty,['config'=>$publish($root['config']),'cardMeta'=>$root['cardMeta'],'cards'=>[]]);
foreach($root['cards'] as $id=>$card)$template['cards'][$id]=array_merge($empty,['config'=>$publish($card['config'])]);
$export=str_replace("=> \n","=>\n",var_export($template,true));
$contents="<?php\n/** Public invitation snapshot for clean clones; generated by tools/export-template.php. */\nreturn ".$export.";\n";
if(file_put_contents($project.'/public-template.php',$contents)===false)throw new RuntimeException('Cannot write public template.');
echo 'Exported '.count($template['cardMeta'])." public invitations. No guests, RSVP, wishes, sessions or passwords exported.\n";
